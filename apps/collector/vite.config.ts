import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { VitePWA } from "vite-plugin-pwa";

// The collector app: the phone UI a collector uses in the street to take the
// daily levy in cash. Same origin as the API through the dev proxy, same
// generated client as the dashboard and the officer app.
export default defineConfig({
  plugins: [
    react(),
    tailwindcss(),
    VitePWA({
      registerType: "prompt",
      workbox: {
        navigateFallback: "/index.html",
        globPatterns: ["**/*.{js,css,html,ico,png,svg,woff2}"],
        // Cash is never recorded offline (the intake needs the ledger), so no
        // API responses are cached: a stale balance is worse than a spinner.
        runtimeCaching: [],
      },
      manifest: {
        name: "TPIRS Collector",
        short_name: "Collector",
        description: "Take the daily levy in cash and keep your float in view.",
        // An explicit id keeps the installed app the same app if start_url ever
        // changes; Chrome falls back to start_url, which is a silent identity
        // change.
        id: "/",
        start_url: "/",
        display: "standalone",
        background_color: "#ffffff",
        theme_color: "#0f172a",
        // Generated by `node scripts/generate-pwa-icons.mjs --out
        // apps/collector/public --mark cash` — real PNGs, because a browser will
        // not offer to install a PWA without them, and the maskable variant keeps
        // the mark inside the circle a launcher crops to.
        icons: [
          { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
          { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
          {
            src: "/icon-maskable-512.png",
            sizes: "512x512",
            type: "image/png",
            purpose: "maskable",
          },
        ],
      },
    }),
  ],
  server: {
    // Bind 0.0.0.0 so a phone on the same network can open the collector app at
    // this machine's LAN IP. Service workers need a secure context, so the PWA
    // install prompt only appears over https or on localhost.
    host: true,
    port: 5175,
    proxy: {
      "/v1": {
        target: "http://localhost:3000",
        changeOrigin: true,
      },
    },
  },
});
